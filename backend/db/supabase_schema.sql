-- BankSense Supabase/Postgres schema.
-- Run this in the Supabase SQL editor on a new project.
-- The backend uses the signed-in user's access token, so these RLS policies
-- are the boundary that keeps each user's complaints private.

create table if not exists public.allowed_users (
    email text primary key check (email = lower(email)),
    note text,
    created_at timestamptz not null default now()
);

create table if not exists public.complaints (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    text text not null,
    normalized_text text not null,
    intent text not null,
    confidence numeric(5, 4) not null check (confidence >= 0 and confidence <= 1),
    model text not null,
    priority text not null,
    priority_reason text not null,
    summary text,
    summary_status text not null check (summary_status in ('enabled', 'unavailable')),
    source text not null default 'submitted' check (source in ('submitted', 'demo')),
    created_at timestamptz not null default now()
);

create index if not exists idx_complaints_user_created
    on public.complaints (user_id, created_at desc, id desc);
create index if not exists idx_complaints_user_intent
    on public.complaints (user_id, intent);
create index if not exists idx_complaints_user_priority
    on public.complaints (user_id, priority);

alter table public.allowed_users enable row level security;
alter table public.complaints enable row level security;

revoke all on table public.allowed_users from anon, authenticated;
revoke all on table public.complaints from anon;
grant usage on schema public to authenticated;

-- Authenticated users may only read their own allowlist row. Only the database
-- owner/service role can add or remove invited emails.
grant select on table public.allowed_users to authenticated;

drop policy if exists "Users can read their own invitation" on public.allowed_users;
create policy "Users can read their own invitation"
    on public.allowed_users
    for select
    to authenticated
    using (lower(email) = lower(auth.jwt() ->> 'email'));

grant select, insert, update, delete on table public.complaints to authenticated;
grant usage, select on sequence public.complaints_id_seq to authenticated;

drop policy if exists "Users can read their own complaints" on public.complaints;
create policy "Users can read their own complaints"
    on public.complaints
    for select
    to authenticated
    using (
        auth.uid() = user_id
        and exists (
            select 1
            from public.allowed_users
            where lower(email) = lower(auth.jwt() ->> 'email')
        )
    );

drop policy if exists "Users can insert their own complaints" on public.complaints;
create policy "Users can insert their own complaints"
    on public.complaints
    for insert
    to authenticated
    with check (
        auth.uid() = user_id
        and exists (
            select 1
            from public.allowed_users
            where lower(email) = lower(auth.jwt() ->> 'email')
        )
    );

drop policy if exists "Users can update their own complaints" on public.complaints;
create policy "Users can update their own complaints"
    on public.complaints
    for update
    to authenticated
    using (
        auth.uid() = user_id
        and exists (
            select 1
            from public.allowed_users
            where lower(email) = lower(auth.jwt() ->> 'email')
        )
    )
    with check (
        auth.uid() = user_id
        and exists (
            select 1
            from public.allowed_users
            where lower(email) = lower(auth.jwt() ->> 'email')
        )
    );

drop policy if exists "Users can delete their own complaints" on public.complaints;
create policy "Users can delete their own complaints"
    on public.complaints
    for delete
    to authenticated
    using (
        auth.uid() = user_id
        and exists (
            select 1
            from public.allowed_users
            where lower(email) = lower(auth.jwt() ->> 'email')
        )
    );
